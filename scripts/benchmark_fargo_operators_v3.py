#!/usr/bin/env python3
"""Benchmark FNO operators on the large transient FARGO dataset.

The v3 benchmark is written for datasets generated by
``scripts/generate_fargo_data_v2.py``.  It keeps the large arrays memory-mapped,
samples temporal transition pairs on the fly, and compares:

* persistence: x(t + dt) = x(t)
* FNO: one-step residual map, span = 1
* FNO-flow: optional variable-span residual map, spans = 1, 2 by default
"""

