def evaluate_semigroup(model, params, ds, case_ids, args, mean, std, loss_weights) -> tuple[float, dict[str, float]]:
    rng = np.random.default_rng(args.seed + 664)
    span_a, span_b = args.consistency_spans
    sq = 0.0
    sq_ch = np.zeros(ds.n_channels, dtype=np.float64)
    samples = 0
    for _ in range(args.eval_batches):
        batch = make_consistency_batch(ds, rng, case_ids, span_a, span_b, args.batch_size, mean, std)
        direct = np.asarray(model.apply(params, set_time_span(batch, batch["t_ab"], batch["dt_ab"])))
        first = model.apply(params, batch)
        second_batch = dict(batch)
        second_batch["x"] = first
        second_batch["t"] = batch["t_b"]
        second_batch["dt"] = batch["dt_b"]
        second = np.asarray(model.apply(params, second_batch))
        err = direct - second
        weighted_err2 = (err**2) * loss_weights
        n = err.shape[0]
        sq += float(np.mean(weighted_err2)) * n
        values = np.mean(weighted_err2, axis=(0, 1, 2))
        sq_ch += np.asarray(values) * n
        samples += n
    return float(math.sqrt(sq / samples)), {
        channel: float(math.sqrt(sq_ch[i] / samples)) for i, channel in enumerate(ds.channels)
    }


def speed_ms_per_batch(model, params, batch, repeats: int) -> float:
    y = model.apply(params, batch)
    y.block_until_ready()
    start = time.perf_counter()
    for _ in range(repeats):
        y = model.apply(params, batch)
    y.block_until_ready()
    return 1000.0 * (time.perf_counter() - start) / repeats


def save_loss_plot(history_by_model: dict[str, list[dict]], output_dir: Path) -> None:
    try:
        os.environ.setdefault("MPLBACKEND", "Agg")
        import matplotlib.pyplot as plt
    except Exception as exc:  # pragma: no cover - optional plotting
        print(f"Skipping loss plot: {exc}")
        return
    for name, history in history_by_model.items():
        rows = [row for row in history if "step" in row]
        if not rows:
            continue
        steps = [row["step"] for row in rows]
        fig, ax = plt.subplots(figsize=(7, 4))
        batch_values = np.asarray([row.get("batch_rmse", 0.0) for row in rows], dtype=np.float64)
        for key, label in [
            ("batch_rmse", "batch"),
            ("train_rmse", "train"),
            ("validation_rmse", "validation"),
            ("consistency_rmse", "consistency"),
        ]:
            values = [row.get(key, 0.0) for row in rows]
            if any(value != 0.0 for value in values):
                ax.plot(steps, values, marker="o", linewidth=1.5, label=label)
        if batch_values.size >= 5 and np.any(batch_values != 0.0):
            window = min(7, batch_values.size)
            kernel = np.ones(window, dtype=np.float64) / window
            smooth = np.convolve(batch_values, kernel, mode="same")
            ax.plot(steps, smooth, linewidth=2.0, label=f"batch ma{window}")
        ax.set_xlabel("step")
        ax.set_ylabel("RMSE")
        ax.set_yscale("log")
        ax.grid(True, alpha=0.25)
        ax.legend()
        fig.tight_layout()
        fig.savefig(output_dir / f"loss_{name}.png", dpi=180)
        plt.close(fig)


def summarize_splits(pair_splits: dict[str, np.ndarray]) -> dict:
    summary = {}
    for split, rows in pair_splits.items():
        spans = {}
        bins = {}
        for _, span, bin_id in rows:
            spans[str(int(span))] = spans.get(str(int(span)), 0) + 1
            bins[str(int(bin_id))] = bins.get(str(int(bin_id)), 0) + 1
        summary[split] = {"pairs": int(rows.shape[0]), "spans": spans, "bins": bins}
    return summary


def run_model(
    name,
    ds,
    coords,
    train_cases,
    val_cases,
    test_cases,
    pair_splits,
    spans,
    args,
    mean,
    std,
    loss_weights,
    seed_offset,
):
    model = make_fno(
        coords,
        args.width,
        args.modes_r,
        args.modes_theta,
        args.depth,
        ds.n_channels,
        radial_kernels=args.radial_kernels,
        radial_dilations=args.radial_dilations,
        radial_padding=args.radial_padding,
    )
    use_consistency = name == "fno_flow" and args.consistency_weight > 0.0
    params, history = train_model(
        name,
        model,
        ds,
        train_cases,
        val_cases if val_cases.size else train_cases,
        pair_splits["train"],
        pair_splits["validation"] if pair_splits["validation"].shape[0] else pair_splits["train"],
        args,
        mean,
        std,
        loss_weights,
        seed_offset,
        use_consistency,
    )
    speed_batch = make_batch(ds, np.random.default_rng(args.seed + 333), test_cases if test_cases.size else train_cases, pair_splits["test"], args.batch_size, mean, std)
    rollout = evaluate_rollout(
        model,
        params,
        ds,
        test_cases if test_cases.size else train_cases,
        args,
        mean,
        std,
        loss_weights,
        args.rollout_horizon,
    )
    sg = sg_ch = None
    if name == "fno_flow":
        sg, sg_ch = evaluate_semigroup(
            model,
            params,
            ds,
            test_cases if test_cases.size else train_cases,
            args,
            mean,
            std,
            loss_weights,
        )
    best = next((row for row in reversed(history) if "best_step" in row), {})
    result = ModelResult(
        train=evaluate_model(model, params, ds, train_cases, pair_splits["train"], args, mean, std, loss_weights),
        validation=evaluate_model(
            model,
            params,
            ds,
            val_cases if val_cases.size else train_cases,
            pair_splits["validation"] if pair_splits["validation"].shape[0] else pair_splits["train"],
            args,
            mean,
            std,
            loss_weights,
        ),
        heldout_time=evaluate_model(model, params, ds, train_cases, pair_splits["test"], args, mean, std, loss_weights),
        heldout_parameter=evaluate_model(
            model,
            params,
            ds,
            test_cases if test_cases.size else val_cases,
            pair_splits["train"],
            args,
            mean,
            std,
            loss_weights,
        ),
        heldout_parameter_time=evaluate_model(
            model,
            params,
            ds,
            test_cases if test_cases.size else val_cases,
            pair_splits["test"],
            args,
            mean,
            std,
            loss_weights,
        ),
        rollout=rollout,
        speed_ms_per_batch=speed_ms_per_batch(model, params, speed_batch, args.speed_repeats),
        trained_steps=max([row.get("step", 0) for row in history]),
        best_step=best.get("best_step"),
        best_validation_rmse=best.get("best_validation_rmse"),
        semigroup_rmse=sg,
        semigroup_rmse_by_channel=sg_ch,
    )
    return result, history


