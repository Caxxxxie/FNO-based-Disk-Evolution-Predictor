def conv_block(x, channels: int, name: str):
    h = hk.Conv2D(channels, kernel_shape=3, padding="SAME", name=f"{name}_conv0")(x)
    h = jax.nn.gelu(h)
    h = hk.Conv2D(channels, kernel_shape=3, padding="SAME", name=f"{name}_conv1")(h)
    return jax.nn.gelu(h)


def polar_periodic_pad(x, radial_pad: int, theta_pad: int, radial_padding: str):
    if radial_pad:
        x = pad_radial(x, radial_pad, radial_padding)
    if theta_pad:
        x = jnp.concatenate([x[:, :, -theta_pad:, :], x, x[:, :, :theta_pad, :]], axis=2)
    return x


def polar_conv2d(
    x,
    channels: int,
    kernel_shape,
    name: str,
    radial_padding: str,
    stride=1,
    with_bias: bool = True,
):
    if isinstance(kernel_shape, int):
        kernel_shape = (kernel_shape, kernel_shape)
    kh, kw = kernel_shape
    h = polar_periodic_pad(x, kh // 2, kw // 2, radial_padding)
    return hk.Conv2D(
        channels,
        kernel_shape=kernel_shape,
        stride=stride,
        padding="VALID",
        with_bias=with_bias,
        name=name,
    )(h)


def periodic_conv_block(x, channels: int, name: str, radial_padding: str):
    h = polar_conv2d(x, channels, 3, f"{name}_conv0", radial_padding)
    h = jax.nn.gelu(h)
    h = polar_conv2d(h, channels, 3, f"{name}_conv1", radial_padding)
    return jax.nn.gelu(h)


def make_unet_stepper(
    coords,
    width,
    levels,
    output_channels: int,
    residual: bool = True,
):
    def forward(batch):
        h = conv_block(grid_inputs(batch, coords), width, "input")
        skips = []
        for level in range(levels):
            skips.append(h)
            channels = width * (2 ** min(level + 1, 3))
            h = hk.Conv2D(channels, kernel_shape=3, stride=2, padding="SAME", name=f"down_{level}")(h)
            h = conv_block(jax.nn.gelu(h), channels, f"down_block_{level}")
        h = conv_block(h, h.shape[-1], "bottleneck")
        for level, skip in reversed(list(enumerate(skips))):
            h = jax.image.resize(h, skip.shape, method="nearest")
            h = jnp.concatenate([h, skip], axis=-1)
            h = conv_block(h, skip.shape[-1], f"up_block_{level}")
        y = hk.Conv2D(output_channels, kernel_shape=1, padding="SAME", name="output")(h)
        return batch["x"] + batch["dt"][:, None, None, :] * y if residual else y

    return hk.without_apply_rng(hk.transform(forward))


def make_periodic_unet_stepper(
    coords,
    width,
    levels,
    output_channels: int,
    radial_padding: str,
    residual: bool = True,
):
    def forward(batch):
        h = periodic_conv_block(grid_inputs(batch, coords), width, "input", radial_padding)
        skips = []
        for level in range(levels):
            skips.append(h)
            channels = width * (2 ** min(level + 1, 3))
            h = polar_conv2d(h, channels, 3, f"down_{level}", radial_padding, stride=2)
            h = periodic_conv_block(jax.nn.gelu(h), channels, f"down_block_{level}", radial_padding)
        h = periodic_conv_block(h, h.shape[-1], "bottleneck", radial_padding)
        for level, skip in reversed(list(enumerate(skips))):
            h = jax.image.resize(h, skip.shape, method="nearest")
            h = jnp.concatenate([h, skip], axis=-1)
            h = periodic_conv_block(h, skip.shape[-1], f"up_block_{level}", radial_padding)
        y = hk.Conv2D(output_channels, kernel_shape=1, padding="SAME", name="output")(h)
        return batch["x"] + batch["dt"][:, None, None, :] * y if residual else y

    return hk.without_apply_rng(hk.transform(forward))


class ConvLSTMCell(hk.Module):
    def __init__(self, hidden_channels: int, name: str | None = None):
        super().__init__(name=name)
        self.hidden_channels = hidden_channels

    def __call__(self, x, h, c):
        gates = hk.Conv2D(
            4 * self.hidden_channels,
            kernel_shape=3,
            padding="SAME",
            name="gates",
        )(jnp.concatenate([x, h], axis=-1))
        i, f, o, g = jnp.split(gates, 4, axis=-1)
        c = jax.nn.sigmoid(f + 1.0) * c + jax.nn.sigmoid(i) * jnp.tanh(g)
        h = jax.nn.sigmoid(o) * jnp.tanh(c)
        return h, c


def make_convlstm_stepper(
    coords,
    width,
    depth,
    recurrent_steps,
    output_channels: int,
    residual: bool = True,
):
    def forward(batch):
        x_prev = batch["x_prev"] if "x_prev" in batch else batch["x"]
        frames = [x_prev, batch["x"]]
        frames.extend([batch["x"]] * max(0, recurrent_steps - len(frames)))
        b, ny, nx, _ = batch["x"].shape
        h = jnp.zeros((b, ny, nx, width), dtype=batch["x"].dtype)
        c = jnp.zeros_like(h)
        cell = ConvLSTMCell(width, name="convlstm_cell")
        for frame in frames:
            h, c = cell(grid_inputs(dict(batch, x=frame), coords), h, c)
        for i in range(max(0, depth - 1)):
            h = hk.Conv2D(width, kernel_shape=3, padding="SAME", name=f"post_conv_{i}")(h)
            h = jax.nn.gelu(h)
        y = hk.Conv2D(output_channels, kernel_shape=1, padding="SAME", name="output")(h)
        return batch["x"] + batch["dt"][:, None, None, :] * y if residual else y

    return hk.without_apply_rng(hk.transform(forward))


def make_model(name: str, coords, args: argparse.Namespace, output_channels: int):
    if name in {"fno", "fno_radial", "fno_flow"}:
        radial_global_mixing = "reflect_fft" if name == "fno_radial" else args.radial_global_mixing
        return make_fno(
            coords,
            args.width,
            args.modes_r,
            args.modes_theta,
            args.depth,
            output_channels,
            radial_kernels=args.radial_kernels,
            radial_dilations=args.radial_dilations,
            radial_padding=args.radial_padding,
            radial_global_mixing=radial_global_mixing,
            radial_global_weight=args.radial_global_weight,
        )
    if name == "plain_fno":
        return make_plain_fno(coords, args.width, args.modes_r, args.modes_theta, args.depth, output_channels)
    if name == "fno_reflect2d":
        return make_reflect_fno(coords, args.width, args.modes_r, args.modes_theta, args.depth, output_channels)
    if name == "unet":
        return make_unet_stepper(coords, args.width, args.unet_levels, output_channels)
    if name == "periodic_unet":
        return make_periodic_unet_stepper(
            coords,
            args.width,
            args.unet_levels,
            output_channels,
            args.radial_padding,
        )
    if name == "convlstm":
        return make_convlstm_stepper(coords, args.width, args.depth, args.convlstm_steps, output_channels)
    raise ValueError(f"Unknown trainable model: {name}")


def batch_mse(pred, target, weights):
    return jnp.mean(((pred - target) ** 2) * weights)


def set_time_span(batch, t, dt):
    out = dict(batch)
    out["t"] = t
    out["dt"] = dt
    return out


def train_model(
    name: str,
    model,
    ds: FargoMemmapDataset,
    train_cases: np.ndarray,
    val_cases: np.ndarray,
    train_pairs: np.ndarray,
    val_pairs: np.ndarray,
    args: argparse.Namespace,
    mean: np.ndarray,
    std: np.ndarray,
    loss_weights: np.ndarray,
    seed_offset: int,
    use_consistency: bool,
) -> tuple[hk.Params, list[dict]]:
    rng = np.random.default_rng(args.seed + seed_offset)
    key = jax.random.PRNGKey(args.seed + seed_offset)
    init_batch = make_batch(ds, rng, train_cases, train_pairs, min(args.batch_size, 2), mean, std)
    params = model.init(key, init_batch)
    opt = optax.chain(optax.clip_by_global_norm(args.grad_clip_norm), optax.adam(args.lr))
    opt_state = opt.init(params)
    span_a, span_b = args.consistency_spans
    loss_weights_jax = jnp.asarray(loss_weights)

    @jax.jit
    def supervised_loss(params, batch):
        pred = model.apply(params, batch)
        return batch_mse(pred, batch["y"], loss_weights_jax)

    @jax.jit
    def total_loss(params, batch, consistency_batch, rollout_batch):
        pred = model.apply(params, batch)
        sup = batch_mse(pred, batch["y"], loss_weights_jax)
        consistency = jnp.asarray(0.0, dtype=sup.dtype)
        if use_consistency:
            direct = model.apply(params, set_time_span(consistency_batch, consistency_batch["t_ab"], consistency_batch["dt_ab"]))
            first = model.apply(params, consistency_batch)
            second_batch = dict(consistency_batch)
            second_batch["x"] = first
            second_batch["t"] = consistency_batch["t_b"]
            second_batch["dt"] = consistency_batch["dt_b"]
            second = model.apply(params, second_batch)
            consistency = batch_mse(direct, second, loss_weights_jax) + batch_mse(
                direct, consistency_batch["y"], loss_weights_jax
            )
        rollout = jnp.asarray(0.0, dtype=sup.dtype)
        if args.rollout_train_weight > 0.0:
            current = rollout_batch["x0"]
            previous = rollout_batch["x_prev"]
            losses = []
            for i in range(args.rollout_train_horizon):
                step_batch = {
                    "x_prev": previous,
                    "x": current,
                    "mu": rollout_batch["mu"],
                    "t": rollout_batch["t"][:, i, :],
                    "dt": rollout_batch["dt"][:, i, :],
                }
                previous = current
                current = model.apply(params, step_batch)
                losses.append(batch_mse(current, rollout_batch["targets"][:, i, ...], loss_weights_jax))
            rollout = sum(losses) / len(losses)
        return sup + args.consistency_weight * consistency + args.rollout_train_weight * rollout, (sup, consistency, rollout)

    @jax.jit
    def train_step(params, opt_state, batch, consistency_batch, rollout_batch):
        (loss, (sup, consistency, rollout)), grads = jax.value_and_grad(total_loss, has_aux=True)(
            params, batch, consistency_batch, rollout_batch
        )
        updates, opt_state = opt.update(grads, opt_state, params)
        return optax.apply_updates(params, updates), opt_state, loss, sup, consistency, rollout

    history = []
    best_params = params
    best_val = math.inf
    best_step = 0
    stale = 0
    empty_consistency = make_consistency_batch(ds, rng, train_cases, span_a, span_b, min(args.batch_size, 2), mean, std)
    empty_rollout = make_rollout_batch(
        ds,
        rng,
        train_cases,
        args.rollout_train_horizon,
        min(args.batch_size, 2),
        mean,
        std,
    )
    for step in range(1, args.steps + 1):
        batch = make_batch(ds, rng, train_cases, train_pairs, args.batch_size, mean, std)
        if use_consistency:
            consistency_batch = make_consistency_batch(ds, rng, train_cases, span_a, span_b, args.batch_size, mean, std)
        else:
            consistency_batch = empty_consistency
        if args.rollout_train_weight > 0.0:
            rollout_batch = make_rollout_batch(
                ds,
                rng,
                train_cases,
                args.rollout_train_horizon,
                args.batch_size,
                mean,
                std,
            )
        else:
            rollout_batch = empty_rollout
        params, opt_state, loss, sup, consistency, rollout = train_step(params, opt_state, batch, consistency_batch, rollout_batch)
        if step == 1 or step % args.eval_every == 0 or step == args.steps:
            train_eval = evaluate_model(
                model,
                params,
                ds,
                train_cases,
                train_pairs,
                args,
                mean,
                std,
                loss_weights,
                max_batches=4,
                include_physics=False,
            )
            val_eval = evaluate_model(
                model,
                params,
                ds,
                val_cases,
                val_pairs,
                args,
                mean,
                std,
                loss_weights,
                max_batches=max(4, args.eval_batches // 2),
                include_physics=False,
            )
            val_rmse = val_eval.rmse
            history.append(
                {
                    "step": step,
                    "batch_rmse": float(jnp.sqrt(loss)),
                    "supervised_rmse": float(jnp.sqrt(sup)),
                    "consistency_rmse": float(jnp.sqrt(consistency)) if use_consistency else 0.0,
                    "rollout_rmse": float(jnp.sqrt(rollout)) if args.rollout_train_weight > 0.0 else 0.0,
                    "train_rmse": train_eval.rmse,
                    "validation_rmse": val_eval.rmse,
                }
            )
            print(f"{name} step {step}: train={train_eval.rmse:.5f} val={val_rmse:.5f}")
            if val_rmse < best_val - args.early_stop_min_delta:
                best_val = val_rmse
                best_params = params
                best_step = step
                stale = 0
            else:
                stale += 1
            if args.early_stop_patience and stale >= args.early_stop_patience:
                print(f"{name} early stopped at step {step}")
                break
    history.append({"best_step": best_step, "best_validation_rmse": best_val})
    return best_params, history


def evaluate_predictions(
    pred_norm: np.ndarray,
    target_norm: np.ndarray,
    mean: np.ndarray,
    std: np.ndarray,
    channels: list[str],
    loss_weights: np.ndarray,
):
    err = pred_norm - target_norm
    weighted_err2 = (err**2) * loss_weights
    rmse_by_channel_values = np.sqrt(np.mean(weighted_err2, axis=(0, 1, 2)))
    pred = pred_norm * std.reshape((1, 1, 1, -1)) + mean.reshape((1, 1, 1, -1))
    target = target_norm * std.reshape((1, 1, 1, -1)) + mean.reshape((1, 1, 1, -1))
    phys_err2 = ((pred - target) ** 2) * loss_weights
    phys_target2 = (target**2) * loss_weights
    return (
        float(np.sqrt(np.mean(weighted_err2))),
        {channel: float(value) for channel, value in zip(channels, rmse_by_channel_values)},
        float(np.sum(phys_err2)),
        float(np.sum(phys_target2)),
        np.sum(phys_err2, axis=(0, 1, 2)),
        np.sum(phys_target2, axis=(0, 1, 2)),
    )


def physical_fields(values_norm: np.ndarray, mean: np.ndarray, std: np.ndarray) -> np.ndarray:
    return values_norm * std.reshape((1, 1, 1, -1)) + mean.reshape((1, 1, 1, -1))


def radial_smooth(values: np.ndarray, window: int) -> np.ndarray:
    if window <= 1:
        return values
    if window % 2 == 0:
        window += 1
    pad = window // 2
    padded = np.pad(values, ((0, 0), (pad, pad)), mode="edge")
    kernel = np.ones(window, dtype=np.float64) / window
    return np.stack([np.convolve(row, kernel, mode="valid") for row in padded], axis=0)


def sigma_reference_profile(r: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    radius = np.maximum(np.asarray(r, dtype=np.float64), 1.0e-12)
    planet_radius = max(float(args.planet_radius), 1.0e-12)
    return float(args.sigma_ref) * (radius / planet_radius) ** (-float(args.sigma_ref_slope))


def count_local_extrema(values: np.ndarray, kind: str, threshold: float) -> int:
    if values.size < 3:
        return 0
    center = values[1:-1]
    if kind == "min":
        mask = (center < values[:-2]) & (center < values[2:]) & (center < threshold)
    elif kind == "max":
        mask = (center > values[:-2]) & (center > values[2:]) & (center > threshold)
    else:
        raise ValueError(f"Unknown extremum kind: {kind}")
    return int(np.count_nonzero(mask))


def gap_ring_features(sigma: np.ndarray, r: np.ndarray, args: argparse.Namespace) -> dict[str, np.ndarray]:
    sigma_bar = sigma.mean(axis=2)
    sigma_bar = radial_smooth(sigma_bar, args.diagnostic_smoothing)
    sigma_ref = sigma_reference_profile(r, args)
    gap_mask = (r >= args.gap_r_min) & (r <= args.gap_r_max)
    ring_mask = (r >= args.ring_r_min) & (r <= args.ring_r_max)
    if not np.any(gap_mask):
        raise ValueError("Gap diagnostic radial window is empty")
    if not np.any(ring_mask):
        raise ValueError("Ring diagnostic radial window is empty")
    r_gap = r[gap_mask]
    r_ring = r[ring_mask]
    gap_profiles = sigma_bar[:, gap_mask] / np.maximum(sigma_ref[gap_mask][None, :], 1.0e-12)
    ring_profiles = sigma_bar[:, ring_mask] / np.maximum(sigma_ref[ring_mask][None, :], 1.0e-12)

    gap_min_idx = np.argmin(gap_profiles, axis=1)
    gap_min = np.take_along_axis(gap_profiles, gap_min_idx[:, None], axis=1)[:, 0]
    gap_center = r_gap[gap_min_idx]
    gap_depth = 1.0 / np.maximum(gap_min, 1.0e-12)
    gap_threshold = np.sqrt(np.maximum(gap_min, 1.0e-24))
    gap_width = np.zeros(gap_profiles.shape[0], dtype=np.float64)
    gap_count = np.zeros(gap_profiles.shape[0], dtype=np.float64)
    for i, profile in enumerate(gap_profiles):
        below = profile <= gap_threshold[i]
        gap_width[i] = float(r_gap[below][-1] - r_gap[below][0]) if np.any(below) else 0.0
        gap_count[i] = count_local_extrema(profile, "min", args.gap_detection_fraction)

    ring_peak_idx = np.argmax(ring_profiles, axis=1)
    ring_peak = np.take_along_axis(ring_profiles, ring_peak_idx[:, None], axis=1)[:, 0]
    ring_peak_radius = r_ring[ring_peak_idx]
    ring_contrast = ring_peak
    ring_count = np.zeros(ring_profiles.shape[0], dtype=np.float64)
    for i, profile in enumerate(ring_profiles):
        ring_count[i] = count_local_extrema(profile, "max", args.ring_detection_factor)

    return {
        "gap_depth": gap_depth,
        "gap_center": gap_center,
        "gap_width": gap_width,
        "gap_count": gap_count,
        "ring_peak_radius": ring_peak_radius,
        "ring_contrast": ring_contrast,
        "ring_count": ring_count,
    }


def wrap_phase(values: np.ndarray) -> np.ndarray:
    return (values + np.pi) % (2.0 * np.pi) - np.pi


def add_gap_ring_metrics(metrics: dict[str, float], pred_sigma: np.ndarray, target_sigma: np.ndarray, r: np.ndarray, args):
    pred = gap_ring_features(pred_sigma, r, args)
    target = gap_ring_features(target_sigma, r, args)
    for name in ["gap_depth", "gap_center", "gap_width", "ring_peak_radius", "ring_contrast"]:
        metrics[f"{name}_abs_error"] = float(np.mean(np.abs(pred[name] - target[name])))
        metrics[f"target_{name}_mean"] = float(np.mean(target[name]))
    for name in ["gap_depth", "ring_contrast"]:
        denom = np.maximum(np.abs(target[name]), 1.0e-12)
        metrics[f"{name}_rel_error_pct"] = float(100.0 * np.mean(np.abs(pred[name] - target[name]) / denom))
    for name in ["gap_count", "ring_count"]:
        metrics[f"{name}_abs_error"] = float(np.mean(np.abs(pred[name] - target[name])))
        metrics[f"{name}_match_fraction"] = float(np.mean(pred[name] == target[name]))
        metrics[f"target_{name}_mean"] = float(np.mean(target[name]))


def add_spiral_metrics(
    metrics: dict[str, float],
    pred_sigma: np.ndarray,
    target_sigma: np.ndarray,
    r: np.ndarray,
    theta: np.ndarray,
    args: argparse.Namespace,
):
    spiral_mask = (r >= args.spiral_r_min) & (r <= args.spiral_r_max)
    if not np.any(spiral_mask):
        raise ValueError("Spiral diagnostic radial window is empty")
    pred_delta = pred_sigma - pred_sigma.mean(axis=2, keepdims=True)
    target_delta = target_sigma - target_sigma.mean(axis=2, keepdims=True)
    r_spiral = r[spiral_mask]
    for mode in args.spiral_modes:
        basis = np.exp(-1j * mode * theta).astype(np.complex64)
        pred_coeff = np.mean(pred_delta * basis[None, None, :], axis=2)[:, spiral_mask]
        target_coeff = np.mean(target_delta * basis[None, None, :], axis=2)[:, spiral_mask]
        phase_diff = wrap_phase(np.angle(pred_coeff) - np.angle(target_coeff))
        target_amp = np.abs(target_coeff)
        pred_amp = np.abs(pred_coeff)
        amp_weight = target_amp / np.maximum(np.mean(target_amp), 1.0e-12)
        metrics[f"spiral_phase_mae_m{mode}_rad"] = float(np.mean(np.abs(phase_diff)))
        metrics[f"spiral_phase_amp_weighted_mae_m{mode}_rad"] = float(
            np.sum(np.abs(phase_diff) * target_amp) / np.maximum(np.sum(target_amp), 1.0e-12)
        )
        amp_num = np.sum((pred_amp - target_amp) ** 2)
        amp_den = np.sum(target_amp**2)
        metrics[f"spiral_amplitude_rel_l2_m{mode}_pct"] = float(100.0 * np.sqrt(amp_num / max(amp_den, 1.0e-24)))
        if r_spiral.size >= 3:
            pred_phase = np.unwrap(np.angle(pred_coeff), axis=1)
            target_phase = np.unwrap(np.angle(target_coeff), axis=1)
            pred_theta = -pred_phase / mode
            target_theta = -target_phase / mode
            pred_dtheta = np.gradient(pred_theta, r_spiral, axis=1)
            target_dtheta = np.gradient(target_theta, r_spiral, axis=1)
            slope_diff = pred_dtheta - target_dtheta
            pred_pitch = np.arctan2(1.0, np.maximum(np.abs(r_spiral[None, :] * pred_dtheta), 1.0e-12))
            target_pitch = np.arctan2(1.0, np.maximum(np.abs(r_spiral[None, :] * target_dtheta), 1.0e-12))
            metrics[f"spiral_phase_slope_amp_weighted_mae_m{mode}"] = float(
                np.sum(np.abs(slope_diff) * amp_weight) / np.maximum(np.sum(amp_weight), 1.0e-12)
            )
            metrics[f"spiral_pitch_amp_weighted_mae_m{mode}_rad"] = float(
                np.sum(np.abs(pred_pitch - target_pitch) * amp_weight) / np.maximum(np.sum(amp_weight), 1.0e-12)
            )


def compute_physics_metrics(
    pred_norm: np.ndarray,
    target_norm: np.ndarray,
    mean: np.ndarray,
    std: np.ndarray,
    channels: list[str],
    r: np.ndarray,
    theta: np.ndarray,
    args: argparse.Namespace,
) -> dict[str, float]:
    if not args.physics_metrics or "log_sigma" not in channels:
        return {}
    log_sigma_idx = channels.index("log_sigma")
    pred = physical_fields(pred_norm, mean, std)
    target = physical_fields(target_norm, mean, std)
    pred_sigma = np.power(10.0, np.clip(pred[..., log_sigma_idx], -12.0, 12.0))
    target_sigma = np.power(10.0, np.clip(target[..., log_sigma_idx], -12.0, 12.0))
    metrics: dict[str, float] = {}
    add_gap_ring_metrics(metrics, pred_sigma, target_sigma, np.asarray(r), args)
    add_spiral_metrics(metrics, pred_sigma, target_sigma, np.asarray(r), np.asarray(theta), args)
    return metrics


def accumulate_physics_metrics(
    sums: dict[str, float],
    pred_norm: np.ndarray,
    target_norm: np.ndarray,
    mean: np.ndarray,
    std: np.ndarray,
    ds: FargoMemmapDataset,
    args: argparse.Namespace,
) -> None:
    metrics = compute_physics_metrics(pred_norm, target_norm, mean, std, ds.channels, ds.r, ds.theta, args)
    n = pred_norm.shape[0]
    for key, value in metrics.items():
        if np.isfinite(value):
            sums[key] = sums.get(key, 0.0) + float(value) * n


def finalize_eval_metrics(
    sum_sq: float,
    sum_sq_ch: np.ndarray,
    samples: int,
    num_sq: float,
    den_sq: float,
    num_sq_ch: np.ndarray,
    den_sq_ch: np.ndarray,
    channels: list[str],
    batches: int,
    rel_l2_floor: float,
    physics_sums: dict[str, float] | None = None,
) -> EvalMetrics:
    floor_sq = rel_l2_floor**2
    physics = None
    if physics_sums:
        physics = {key: float(value / samples) for key, value in sorted(physics_sums.items())}
    return EvalMetrics(
        rmse=float(math.sqrt(sum_sq / samples)),
        rmse_by_channel={channel: float(math.sqrt(sum_sq_ch[i] / samples)) for i, channel in enumerate(channels)},
        rel_l2_pct=float(100.0 * math.sqrt(num_sq / max(den_sq, floor_sq))),
        rel_l2_pct_by_channel={
            channel: float(100.0 * math.sqrt(num_sq_ch[i] / max(den_sq_ch[i], floor_sq)))
            for i, channel in enumerate(channels)
        },
        batches=batches,
        samples=samples,
        physics=physics,
    )


def evaluate_model(
    model,
    params,
    ds,
    case_ids,
    pair_rows,
    args,
    mean,
    std,
    loss_weights,
    max_batches=None,
    include_physics: bool = True,
) -> EvalMetrics:
    batches = args.eval_batches if max_batches is None else max_batches
    rng = np.random.default_rng(args.seed + 991)
    sum_sq = 0.0
    sum_sq_ch = np.zeros(ds.n_channels, dtype=np.float64)
    num_sq = 0.0
    den_sq = 0.0
    num_sq_ch = np.zeros(ds.n_channels, dtype=np.float64)
    den_sq_ch = np.zeros(ds.n_channels, dtype=np.float64)
    physics_sums: dict[str, float] = {}
    samples = 0
    for _ in range(batches):
        batch = make_batch(ds, rng, case_ids, pair_rows, args.batch_size, mean, std)
        pred_norm = np.asarray(model.apply(params, batch))
        target_norm = np.asarray(batch["y"])
        rmse, rmse_ch, batch_num, batch_den, batch_num_ch, batch_den_ch = evaluate_predictions(
            pred_norm, target_norm, mean, std, ds.channels, loss_weights
        )
        if include_physics:
            accumulate_physics_metrics(physics_sums, pred_norm, target_norm, mean, std, ds, args)
        n = pred_norm.shape[0]
        sum_sq += (rmse**2) * n
        for i, channel in enumerate(ds.channels):
            sum_sq_ch[i] += (rmse_ch[channel] ** 2) * n
        num_sq += batch_num
        den_sq += batch_den
        num_sq_ch += batch_num_ch
        den_sq_ch += batch_den_ch
        samples += n
    return finalize_eval_metrics(
        sum_sq,
        sum_sq_ch,
        samples,
        num_sq,
        den_sq,
        num_sq_ch,
        den_sq_ch,
        ds.channels,
        batches,
        args.rel_l2_floor,
        physics_sums,
    )


